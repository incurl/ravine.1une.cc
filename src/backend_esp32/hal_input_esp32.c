/*
 * hal_input_esp32.c — ESP32-S3 input backend.
 *
 * Wraps the legacy driver main/ui/buttons.c (the matrix scanner) plus
 * main/ui/knobs.c and main/ui/encoder.c for the analog controls.
 *
 * Event-model reconciliation
 * --------------------------
 * The legacy scanner emits ONE event per press: either a "tap" (fired
 * on release) or a "long press" (fired once the hold threshold passes).
 * The HAL contract asks for four distinct states.
 *
 * This backend derives the richer model from the legacy primitives:
 *
 *   KEY_PRESS / KEY_RELEASE   edge-detected from buttons_is_pressed(),
 *                             which reports the live debounced state of
 *                             every key.
 *   KEY_LONG_PRESS            taken from the legacy long-press event.
 *   KEY_HOLD                  generated by this backend while a key is
 *                             held, repeating every
 *                             SYNTH_KEY_HOLD_REPEAT_MS.
 *
 * The legacy "tap" event is intentionally NOT forwarded: the
 * KEY_RELEASE that the edge detector already emits carries the same
 * information with better timing, and forwarding both would double
 * every press in the application layer.
 *
 * Ownership rule (transition period)
 * ----------------------------------
 * buttons_tick() must have exactly ONE caller. The legacy
 * button_scan_task in main/main.c calls it. While that task is still
 * running, this backend must NOT also tick the scanner, or every
 * matrix scan would happen twice and events would double up.
 */
