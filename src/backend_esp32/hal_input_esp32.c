/* The board header must agree with the firmware's own pin map. */
_Static_assert(SYNTH_KEY_ROWS == BTN_ROW_COUNT, "row count mismatch");
_Static_assert(SYNTH_KEY_COLS == BTN_COL_COUNT, "column count mismatch");
_Static_assert(SYNTH_KEY_DEDICATED_COUNT == BTN_GPIO_COUNT, "dedicated count mismatch");
_Static_assert(SYNTH_KEY_TOTAL_COUNT == BTN_COUNT, "total key count mismatch");
_Static_assert(SYNTH_KEY_DEBOUNCE_MS == BTN_DEBOUNCE_MS, "debounce mismatch");
_Static_assert(SYNTH_KEY_LONG_PRESS_MS == BTN_LONG_PRESS_MS, "long-press mismatch");
_Static_assert(SYNTH_KEY_BTN_SOUND == BTN_SOUND, "SOUND id mismatch");
_Static_assert(SYNTH_KEY_BTN_PATTERN == BTN_PATTERN, "PATTERN id mismatch");
_Static_assert(SYNTH_KEY_BTN_BPM == BTN_BPM, "BPM id mismatch");
_Static_assert(SYNTH_KEY_BTN_REC == BTN_REC, "REC id mismatch");
_Static_assert(SYNTH_KEY_BTN_FX == BTN_FX, "FX id mismatch");
_Static_assert(SYNTH_KEY_BTN_PLAY == BTN_PLAY, "PLAY id mismatch");
_Static_assert(SYNTH_KEY_BTN_WRITE == BTN_WRITE, "WRITE id mismatch");
_Static_assert(SYNTH_KEY_STEP1 == BTN_STEP1, "STEP1 id mismatch");

static const char *TAG = "hal_input";

/* Queue depth. The legacy driver uses 64; match it so a burst of
 * presses is never dropped during a scan gap. */
#define INPUT_QUEUE_DEPTH 64

static event_queue_t *s_queue;
static bool            s_initialised;

/* Live debounced state of every key, used for edge detection. */
static bool s_pressed[SYNTH_KEY_TOTAL_COUNT];
/* Timestamp of the last HOLD event emitted for each key. */
static int64_t s_hold_at[SYNTH_KEY_TOTAL_COUNT];
/* Whether the key is currently in a HOLD repeat series. */
static bool s_holding[SYNTH_KEY_TOTAL_COUNT];

/* Last reported knob positions, for delta computation. */
static uint8_t s_knob_a_last;
static uint8_t s_knob_b_last;
/* True once the first knob sample has been taken. */
static bool    s_knob_seeded;


/* ─── Helpers ───────────────────────────────────────────────────── */

/* Matrix coordinates for a key id, or SYNTH_COORD_NONE for a
 * dedicated (non-matrix) button. */
static void key_coords(uint8_t key_id, uint8_t *row, uint8_t *col)
{
    if (key_id >= SYNTH_KEY_MATRIX_FIRST &&
        key_id < SYNTH_KEY_MATRIX_FIRST + SYNTH_KEY_MATRIX_COUNT) {
        int idx = key_id - SYNTH_KEY_MATRIX_FIRST;
        *row = (uint8_t)(idx / SYNTH_KEY_COLS);
        *col = (uint8_t)(idx % SYNTH_KEY_COLS);
    } else {
        *row = SYNTH_COORD_NONE;
        *col = SYNTH_COORD_NONE;
    }
}

static void push_event(hal_input_event_type_t type,
                       uint8_t key_id,
                       int32_t value)
{
    hal_input_event_t ev;
    ev.type         = type;
    ev.key_id       = key_id;
    ev.value        = value;
    ev.timestamp_ms = (uint64_t)(esp_timer_get_time() / 1000);
    key_coords(key_id, &ev.row, &ev.column);

    if (event_queue_push(s_queue, &ev) != SYS_OK) {
        HAL_LOG_WARN(TAG, "input queue full, dropping event");
    }
}

/* ─── Init ──────────────────────────────────────────────────────── */

sys_status_t hal_input_init(void)
{
    if (s_initialised) {
        return SYS_OK;
    }

    /* The legacy driver owns the GPIO setup and the debounce state. */
    esp_err_t err = buttons_init();
    if (err != ESP_OK) {
        HAL_LOG_ERROR(TAG, "buttons_init failed: %s", esp_err_to_name(err));
        return SYS_ERR_IO;
    }

    err = knobs_init();
    if (err != ESP_OK) {
        HAL_LOG_ERROR(TAG, "knobs_init failed: %s", esp_err_to_name(err));
        return SYS_ERR_IO;
    }

    /* The encoder is optional in the HAL: a device without it still
     * works, it just cannot scroll. */
    if (encoder_init() != ESP_OK) {
        HAL_LOG_WARN(TAG, "encoder unavailable; continuing without it");
    }

    sys_status_t st = event_queue_create(sizeof(hal_input_event_t),
                                         INPUT_QUEUE_DEPTH,
                                         &s_queue);
    if (st != SYS_OK) {
        HAL_LOG_ERROR(TAG, "event queue creation failed");
        return st;
    }

    memset(s_pressed, 0, sizeof(s_pressed));
    memset(s_hold_at, 0, sizeof(s_hold_at));
    memset(s_holding, 0, sizeof(s_holding));
    s_knob_seeded = false;

    s_initialised = true;
    HAL_LOG_INFO(TAG, "input HAL ready: %d keys, %dx%d matrix",
                 SYNTH_KEY_TOTAL_COUNT, SYNTH_KEY_ROWS, SYNTH_KEY_COLS);
    return SYS_OK;
}

sys_status_t hal_input_deinit(void)
{
    if (!s_initialised) {
        return SYS_OK;
    }
    event_queue_destroy(s_queue);
    s_queue       = NULL;
    s_initialised = false;
    return SYS_OK;
}

/* ─── Tick: derive HAL events from the legacy primitives ────────── */

void hal_input_tick(void)
{
    if (!s_initialised) {
        return;
    }

    const int64_t now = esp_timer_get_time() / 1000;

    /* 1. Drain the legacy queue for long-press events.
     *
     * The legacy "tap" is dropped on purpose: KEY_RELEASE already
     * carries that information. Only the long-press is forwarded. */
    for (;;) {
        button_event_t legacy = buttons_pop();
        if (legacy.btn_id == 0xFF) {
            break;                      /* queue empty */
        }
        if (legacy.long_press && legacy.btn_id < SYNTH_KEY_TOTAL_COUNT) {
            push_event(HAL_INPUT_KEY_LONG_PRESS, legacy.btn_id, 0);
        }
    }

    /* 2. Edge-detect every key from its live debounced state. */
    for (uint8_t id = 0; id < SYNTH_KEY_TOTAL_COUNT; id++) {
        bool now_pressed = buttons_is_pressed(id);

        if (now_pressed != s_pressed[id]) {
            s_pressed[id] = now_pressed;
            if (now_pressed) {
                push_event(HAL_INPUT_KEY_PRESS, id, 0);
                s_holding[id]   = true;
                s_hold_at[id]   = now;
            } else {
                push_event(HAL_INPUT_KEY_RELEASE, id, 0);
                s_holding[id]   = false;
            }
            continue;
        }

        /* 3. HOLD repeats while the key stays down. */
        if (now_pressed && s_holding[id] &&
            (now - s_hold_at[id]) >= SYNTH_KEY_HOLD_REPEAT_MS) {
            s_hold_at[id] = now;
            push_event(HAL_INPUT_KEY_HOLD, id, 0);
        }
    }

    /* 4. Knob deltas. The legacy driver already smooths the ADC and
     * applies a dead zone, so the raw difference is meaningful. */
    knobs_tick();
    uint8_t ka = knobs_get_a();
    uint8_t kb = knobs_get_b();

    if (!s_knob_seeded) {
        s_knob_a_last = ka;
        s_knob_b_last = kb;
        s_knob_seeded  = true;
    } else {
        if (ka != s_knob_a_last) {
            push_event(HAL_INPUT_KNOB_DELTA, SYNTH_KNOB_A,
                       (int32_t)ka - (int32_t)s_knob_a_last);
            s_knob_a_last = ka;
        }
        if (kb != s_knob_b_last) {
            push_event(HAL_INPUT_KNOB_DELTA, SYNTH_KNOB_B,
                       (int32_t)kb - (int32_t)s_knob_b_last);
            s_knob_b_last = kb;
        }
    }

    /* 5. Rotary encoder detents. */
    encoder_tick();
    int8_t delta = encoder_get_delta();
    if (delta != 0) {
        push_event(HAL_INPUT_ENCODER_DELTA, 0, (int32_t)delta);
    }
}

/* ─── Consumer API ──────────────────────────────────────────────── */

bool hal_input_pop(hal_input_event_t *out)
{
    if (out == NULL || !s_initialised) {
        return false;
    }
    return event_queue_pop(s_queue, out) == SYS_OK;
}

bool hal_input_is_pressed(uint8_t key_id)
{
    if (!s_initialised || key_id >= SYNTH_KEY_TOTAL_COUNT) {
        return false;
    }
    return buttons_is_pressed(key_id);
}

size_t hal_input_pending(void)
{
    if (!s_initialised) {
        return 0;
    }
    return event_queue_count(s_queue);
}

void hal_input_flush(void)
{
    if (!s_initialised) {
        return;
    }
    event_queue_clear(s_queue);
}

bool hal_input_quit_requested(void)
{
    /* The device has no window to close. Quitting is handled by the
     * power-management path, not by the input HAL. */
    return false;
}

